  const TOTAL_MS = 80 * 60 * 1000;

  let savedTime = 0;
  let startedAt = null;
  let clock = null;

  function elapsedTime() {
    if (startedAt === null) {
      return savedTime;
    }

    return savedTime + Date.now() - startedAt;
  }

  function formatTime(ms) {
    const allSeconds = Math.floor(ms / 1000);
    const minutes = Math.floor(allSeconds / 60);
    const seconds = allSeconds % 60;

    return (
      String(minutes).padStart(2, "0") +
      ":" +
      String(seconds).padStart(2, "0")
    );
  }

  function updateTimer() {
    const elapsed = Math.min(
      elapsedTime(),
      TOTAL_MS
    );

    const remaining = Math.max(
      TOTAL_MS - elapsed,
      0
    );

    $("timer").textContent =
      formatTime(elapsed);

    $("remaining").textContent =
      remaining > 0
        ? "Қалғаны: " + formatTime(remaining)
        : "80 минут аяқталды";

    if (remaining === 0 && startedAt !== null) {
      pauseTimer();
    }
  }

  function startTimer() {
    if (startedAt !== null) return;

    if (savedTime >= TOTAL_MS) {
      savedTime = 0;
    }

    startedAt = Date.now();

    clock = setInterval(updateTimer, 500);

    updateTimer();
  }

  function pauseTimer() {
    if (startedAt === null) return;

    savedTime = Math.min(
      elapsedTime(),
      TOTAL_MS
    );

    startedAt = null;

    clearInterval(clock);
    clock = null;

    updateTimer();
  }

  function resetTimer() {
    pauseTimer();
    savedTime = 0;
    updateTimer();
  }

